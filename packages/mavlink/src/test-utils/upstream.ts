/**
 * Test-only: runs upstream `modules/MAVLink/mavlink.js` (pymavlink-generated, with its runtime
 * fixes) in a `node:vm` context so this package can be compared with it on identical bytes.
 * Upstream takes its Node path (CommonJS `require` of jspack, `events`, `util`), so
 * `mavlink20.ready` is already resolved; it is awaited anyway, as its README requires.
 */
import { readFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createContext, runInContext } from 'node:vm'

const UPSTREAM_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '../../../../upstream')
export const UPSTREAM_MAVLINK = resolve(UPSTREAM_DIR, 'modules/MAVLink/mavlink.js')

