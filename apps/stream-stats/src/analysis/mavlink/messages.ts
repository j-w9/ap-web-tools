/** Name of a known component id, e.g. `"MAV_COMP_ID_AUTOPILOT1"`. */
export type MavComponentName = (typeof MAV_COMPONENTS)[number]['name']

const MESSAGE_BY_ID: ReadonlyMap<number, (typeof MAVLINK_MESSAGES)[number]> = new Map(MAVLINK_MESSAGES.map((m) => [m.id, m]))
const COMPONENT_BY_ID: ReadonlyMap<number, MavComponentName> = new Map(MAV_COMPONENTS.map((c) => [c.id, c.name]))

/** Definition of a message id, or `undefined` if the id is not in the table. */
export function mavlinkMessage(id: number): (typeof MAVLINK_MESSAGES)[number] | undefined {
  return MESSAGE_BY_ID.get(id)
}

/** `MAV_COMPONENT` name of a component id, or `undefined` for ids without one. */
export function mavComponentName(id: number): MavComponentName | undefined {
  return COMPONENT_BY_ID.get(id)
}
